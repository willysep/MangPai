    const branches = data.BRANCHES;
    const hidden = data.HIDDEN;
    const stemHe = data.STEM_HE;

    const isStemHe = (s1, s2) => {
      for (let k = 0; k < stemHe.length; k++) {
        const [a, b, wx] = stemHe[k];
        if ((a === s1 && b === s2) || (a === s2 && b === s1)) {
          return wx;
        }
      }
      return null;
    };

